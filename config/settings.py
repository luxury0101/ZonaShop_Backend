def obtener_lista_entorno(nombre, valor_predeterminado=""):
    return [
        elemento.strip()
        for elemento in os.getenv(
            nombre,
            valor_predeterminado,
        ).split(",")
        if elemento.strip()
    ]


def obtener_booleano_entorno(nombre, valor_predeterminado=False):
    valor = os.getenv(nombre)

    if valor is None:
        return valor_predeterminado

    valor_normalizado = valor.strip().lower()
    valores_validos = {
        "true": True,
        "1": True,
        "yes": True,
        "on": True,
        "false": False,
        "0": False,
        "no": False,
        "off": False,
    }

    if valor_normalizado not in valores_validos:
        raise RuntimeError(
            f"{nombre} debe contener un valor booleano válido."
        )

    return valores_validos[valor_normalizado]


